//! The 48 contiguous United States, with the Canadian and Mexican borders as coast.
//! The Great Lakes are sea; Long Island, the Keys and the islands are left out.

use super::{Data, Geo};

pub(super) fn data() -> Data {
    let mut ring = PACIFIC.to_vec();
    ring.extend_from_slice(MEXICO_BORDER);
    ring.extend_from_slice(GULF);
    ring.extend_from_slice(ATLANTIC);
    ring.extend_from_slice(CANADA_BORDER);
    Data {
        name: "United States",
        blurb: "The lower 48, coast to coast. The Rockies and the Appalachians split it; the Great Lakes are sea.",
        rings: vec![ring],
        bridges: &[&[(-84.73, 45.75), (-84.73, 45.9)]],
        fits: |_| true,
        ranges: RANGES.to_vec(),
        uplands: UPLANDS.to_vec(),
        places: PLACES.to_vec(),
    }
}

