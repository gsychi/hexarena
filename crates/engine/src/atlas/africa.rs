//! Mainland Africa, cut from Asia at the Suez Canal. Madagascar and the islands are
//! left out.

use super::{mediterranean, Data, Geo};

pub(super) fn data() -> Data {
    let shore = mediterranean::SOUTH_AND_EAST_SHORE;
    let at = |p: Geo| shore.iter().position(|&q| q == p).expect("a point on the Mediterranean shore");
    let mut ring = vec![(-5.8, 35.78)];
    ring.extend(shore[at((32.3, 31.25))..].iter().rev());
    ring.extend_from_slice(RED_SEA_TO_CAPE);
    ring.extend_from_slice(CAPE_TO_TANGIER);
    let mut ranges = mediterranean::RANGES[..4].to_vec();
    ranges.extend_from_slice(RANGES);
    Data {
        name: "Africa",
        blurb: "The whole continent, Cairo to the Cape. Sahara in the north, the Rift and the Ethiopian Highlands in the east.",
        rings: vec![ring],
        bridges: &[],
        fits: |_| true,
        ranges,
        uplands: UPLANDS.to_vec(),
        places: PLACES.to_vec(),
    }
}

