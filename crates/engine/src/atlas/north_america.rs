//! Alaska to Panama. The Arctic islands, Greenland, Newfoundland, Vancouver Island and
//! the Caribbean are left out. Hudson Bay and the Great Lakes are water, and the thin
//! isthmuses (Central America, Baja, Florida, the Alaska Peninsula) are kept as land.

use super::{usa, Data, Geo};

pub(super) fn data() -> Data {
    let rev = |s: &[Geo]| s.iter().rev().copied().collect::<Vec<_>>();
    let mut ring = rev(usa::PACIFIC);
    ring.extend_from_slice(NORTH);
    ring.extend(rev(usa::ATLANTIC));
    ring.extend(rev(usa::GULF));
    ring.extend_from_slice(SOUTH);
    let mut ranges = usa::RANGES.to_vec();
    ranges.extend_from_slice(RANGES);
    let mut uplands = usa::UPLANDS.to_vec();
    uplands.extend_from_slice(UPLANDS);
    Data {
        name: "North America",
        blurb: "Alaska to Panama: Canada, the States and Mexico. Hudson Bay and the Great Lakes cut into the middle.",
        rings: vec![ring, SUPERIOR.to_vec(), MICHIGAN.to_vec(), HURON.to_vec(), ERIE.to_vec(), ONTARIO.to_vec()],
        bridges: BRIDGES,
        fits: |_| true,
        ranges,
        uplands,
        places: PLACES.to_vec(),
    }
}

