/// The Latvian and Estonian coast sits in the board's pinched north-east corner, so it
/// may be cut by the edge like the inland cut in the east.
fn fits((lon, lat): Geo) -> bool {
    lon < 35.0 && !(lon > 20.5 && lat > 55.5)
}

